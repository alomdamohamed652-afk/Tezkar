import test from "node:test";
import assert from "node:assert/strict";
import pg from "pg";
import { randomUUID } from "node:crypto";
import { inspectDatabaseTransfer } from "../src/modules/data-transfer/data-transfer-inspection.service.js";
import { buildTransferPlan } from "../src/modules/data-transfer/data-transfer-plan.service.js";
import { createReadOnlySourcePool, createTargetPool } from "../src/modules/data-transfer/data-transfer-connection.service.js";
import { assertDisposableDatabaseUrl } from "./helpers/disposable-database-url.js";

const adminUrl = process.env.TEST_DATABASE_URL;

test("database transfer inspection compares two real disposable PostgreSQL databases", {
  skip: !adminUrl ? "TEST_DATABASE_URL is not configured" : false,
  timeout: 60_000
}, async () => {
  assertDisposableDatabaseUrl(adminUrl!);
  const admin = new pg.Pool({ connectionString: adminUrl, max: 1 });
  const suffix = randomUUID().replaceAll("-", "").slice(0, 16);
  const sourceName = `transfer_source_${suffix}`;
  const targetName = `transfer_target_${suffix}`;
  const quoteDb = (name: string) => '"' + name.replaceAll('"', '""') + '"';
  const databaseUrl = (name: string) => {
    const url = new URL(adminUrl!);
    url.pathname = `/${name}`;
    return url.toString();
  };
  let sourceCreated = false;
  let targetCreated = false;
  const restrictedRole = `transfer_reader_${suffix}`;
  const restrictedPassword = randomUUID().replaceAll("-", "");
  let restrictedRoleCreated = false;

  const fixtureSql = `
    CREATE EXTENSION IF NOT EXISTS postgres_fdw;
    CREATE SERVER worker_events_server FOREIGN DATA WRAPPER postgres_fdw
      OPTIONS (host '127.0.0.1', dbname 'unused');
    CREATE FOREIGN TABLE public.remote_workers (id bigint)
      SERVER worker_events_server OPTIONS (schema_name 'public', table_name 'workers');

    CREATE TYPE public.worker_state AS ENUM ('active', 'paused');
    CREATE DOMAIN public.positive_amount AS numeric(12,2)
      CHECK (VALUE >= 0)
      CHECK (VALUE <= 9999999999);
    CREATE TYPE public.worker_summary AS (worker_id bigint, label text);

    CREATE TABLE public.workers (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name text NOT NULL,
      state public.worker_state NOT NULL DEFAULT 'active',
      balance public.positive_amount NOT NULL DEFAULT 0
    );
    CREATE TABLE public.orders (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      worker_id bigint NOT NULL REFERENCES public.workers(id),
      amount numeric(12,2) NOT NULL CHECK (amount >= 0),
      CONSTRAINT orders_worker_amount_unique UNIQUE (worker_id, amount)
    );
    CREATE TABLE public.worker_events (
      id bigint NOT NULL,
      event_date date NOT NULL,
      PRIMARY KEY (id, event_date)
    ) PARTITION BY RANGE (event_date);
    CREATE TABLE public.worker_events_2026 PARTITION OF public.worker_events
      FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

    CREATE INDEX workers_name_partial_idx
      ON public.workers (lower(name)) INCLUDE (state) WHERE state = 'active';

    CREATE SEQUENCE public.audit_sequence START WITH 7 INCREMENT BY 2;
    CREATE TABLE public.audit_log (
      id bigint PRIMARY KEY DEFAULT nextval('public.audit_sequence'),
      event text NOT NULL
    );
    ALTER SEQUENCE public.audit_sequence OWNED BY public.audit_log.id;

    CREATE VIEW public.worker_balances AS
      SELECT id, name, balance FROM public.workers;
    CREATE MATERIALIZED VIEW public.worker_order_totals AS
      SELECT worker_id, sum(amount) AS total FROM public.orders GROUP BY worker_id;

    CREATE FUNCTION public.touch_audit_log() RETURNS trigger
      LANGUAGE plpgsql AS $$
      BEGIN
        INSERT INTO public.audit_log(event) VALUES ('worker:' || NEW.id::text);
        RETURN NEW;
      END;
      $$;
    CREATE TRIGGER workers_audit_trigger
      AFTER INSERT ON public.workers
      FOR EACH ROW EXECUTE FUNCTION public.touch_audit_log();

    CREATE FUNCTION public.worker_label(bigint) RETURNS text
      LANGUAGE sql IMMUTABLE AS $$ SELECT 'worker-' || $1::text $$;
    CREATE PROCEDURE public.refresh_worker_totals()
      LANGUAGE sql AS $$ REFRESH MATERIALIZED VIEW public.worker_order_totals $$;
    CREATE FUNCTION public.worker_rank(bigint) RETURNS bigint
      LANGUAGE sql IMMUTABLE WINDOW AS $$ SELECT $1 $$;

    ALTER TABLE public.workers ENABLE ROW LEVEL SECURITY;
    CREATE POLICY workers_read_policy ON public.workers
      FOR SELECT USING (true);

    INSERT INTO public.workers(name, state, balance)
      VALUES ('fixture-worker', 'active', 125.50);
    INSERT INTO public.orders(worker_id, amount)
      SELECT id, 50.00 FROM public.workers WHERE name = 'fixture-worker';
  `;

  try {
    await admin.query(`CREATE DATABASE ${quoteDb(sourceName)}`);
    sourceCreated = true;
    await admin.query(`CREATE DATABASE ${quoteDb(targetName)}`);
    targetCreated = true;

    for (const name of [sourceName, targetName]) {
      const pool = new pg.Pool({ connectionString: databaseUrl(name), max: 1 });
      try {
        await pool.query(fixtureSql);
      } finally {
        await pool.end();
      }
    }

    const result = await inspectDatabaseTransfer(databaseUrl(sourceName), databaseUrl(targetName));

    assert.equal(result.source.tableCount, 5);
    assert.equal(result.target.tableCount, 5);
    assert.equal(result.source.foreignKeyCount, 1);
    assert.equal(result.target.foreignKeyCount, 1);
    assert.ok(result.blockers.some(item =>
      item.table === "public.remote_workers" && item.status === "unsupported_relation"
    ), "foreign tables must be surfaced as explicit blockers even when present on both sides");
    assert.deepEqual(result.unsupportedRelations, {
      source: ["public.remote_workers"],
      target: ["public.remote_workers"]
    });
    const unsupportedPlan = buildTransferPlan(result.comparison, ["FOREIGN TABLES غير المدعومة"]);
    assert.equal(unsupportedPlan.readyOrder.length, 0,
      "unsupported foreign tables must prevent the entire plan from claiming readiness");
    assert.equal(result.comparison.find(item => item.table === "public.worker_events")?.status, "compatible");
    assert.equal(result.comparison.find(item => item.table === "public.worker_events_2026")?.status, "compatible");
    assert.equal(result.sourceFeatures.views, 1);
    assert.equal(result.sourceFeatures.materializedViews, 1);
    assert.equal(result.sourceFeatures.triggers, 1);
    assert.equal(result.sourceFeatures.customTypes, 3);
    assert.equal(result.sourceFeatures.routines, 9);
    assert.equal(result.sourceFeatures.sequences, 3);
    assert.equal(result.targetFeatures.views, 1);
    assert.equal(result.targetFeatures.materializedViews, 1);
    assert.equal(result.targetFeatures.triggers, 1);
    assert.equal(result.targetFeatures.customTypes, 3);
    assert.equal(result.targetFeatures.routines, 9);
    assert.equal(result.targetFeatures.sequences, 3);
    assert.ok(result.objectComparison.views.differences.missingInTarget.length === 0);
    assert.ok(result.objectComparison.triggers.differences.missingInTarget.length === 0);
    assert.ok(result.objectComparison.routines.differences.missingInTarget.length === 0);
    assert.ok(result.objectComparison.sequences.differences.missingInTarget.length === 0);
    for (const objectName of [
      "indexes", "constraints", "views", "materializedViews", "triggers",
      "extensions", "customTypes", "routines", "sequences"
    ] as const) {
      assert.equal(
        result.objectComparison[objectName].source,
        result.objectComparison[objectName].target,
        `expected matching ${objectName} metadata`
      );
    }

    // A same-named ENUM with different labels and a same-named sequence with
    // different settings must not be treated as globally compatible.
    const renamedTarget = new pg.Pool({ connectionString: databaseUrl(targetName), max: 1 });
    try {
      await renamedTarget.query("ALTER INDEX public.workers_name_partial_idx RENAME TO workers_name_partial_renamed");
    } finally {
      await renamedTarget.end();
    }
    const renamedIndexOnly = await inspectDatabaseTransfer(databaseUrl(sourceName), databaseUrl(targetName));
    assert.deepEqual(
      renamedIndexOnly.objectComparison.indexes.differences,
      { missingInTarget: [], missingInSource: [] },
      "an index name-only change must not be treated as a structural difference"
    );

    const changedTarget = new pg.Pool({ connectionString: databaseUrl(targetName), max: 1 });
    try {
      await changedTarget.query("ALTER INDEX public.workers_name_partial_renamed RENAME TO workers_name_partial_idx");
      await changedTarget.query("ALTER TYPE public.worker_state ADD VALUE 'archived'");
      await changedTarget.query("ALTER TABLE public.workers DISABLE TRIGGER workers_audit_trigger");
      await changedTarget.query("ALTER VIEW public.worker_balances SET (security_barrier = true)");
      await changedTarget.query("ALTER FUNCTION public.worker_label(bigint) SECURITY DEFINER");
      await changedTarget.query("ALTER TABLE public.worker_events DETACH PARTITION public.worker_events_2026");
      await changedTarget.query("DROP INDEX public.workers_name_partial_idx");
      await changedTarget.query("CREATE INDEX workers_name_partial_idx ON public.workers (lower(name)) INCLUDE (state) WHERE state = 'paused'");
      await changedTarget.query("ALTER DOMAIN public.positive_amount ADD CONSTRAINT positive_amount_not_special CHECK (VALUE <> 12345)");
      await changedTarget.query("ALTER SEQUENCE public.audit_sequence INCREMENT BY 3");
    } finally {
      await changedTarget.end();
    }
    const changedObjects = await inspectDatabaseTransfer(databaseUrl(sourceName), databaseUrl(targetName));
    assert.ok(changedObjects.objectComparison.customTypes.differences.missingInTarget.length > 0);
    assert.ok(changedObjects.objectComparison.customTypes.differences.missingInSource.length > 0);
    assert.ok(changedObjects.objectComparison.sequences.differences.missingInTarget.length > 0);
    assert.ok(changedObjects.objectComparison.indexes.differences.missingInTarget.length > 0);
    assert.ok(changedObjects.objectComparison.triggers.differences.missingInTarget.length > 0,
      "trigger enabled/disabled state must be compared");
    assert.ok(changedObjects.objectComparison.views.differences.missingInTarget.length > 0,
      "view security options must be compared");
    assert.ok(changedObjects.objectComparison.routines.differences.missingInTarget.length > 0,
      "routine security properties must be compared");
    assert.ok(changedObjects.comparison.some(item =>
      item.table === "public.worker_events" && item.status === "schema_mismatch"
    ), "partition detach must be detected");
    assert.ok(changedObjects.comparison.some(item =>
      item.table === "public.workers" && item.status === "schema_mismatch"
    ));
    const globalBlockers = [
      "indexes", "constraints", "views", "materializedViews", "triggers",
      "extensions", "customTypes", "routines", "sequences"
    ].flatMap(key => {
      const item = changedObjects.objectComparison[key as keyof typeof changedObjects.objectComparison];
      return item && (item.differences.missingInTarget.length > 0 || item.differences.missingInSource.length > 0)
        ? [key]
        : [];
    });
    const blockedPlan = buildTransferPlan(changedObjects.comparison, globalBlockers);
    assert.equal(blockedPlan.readyOrder.length, 0);
    assert.equal(blockedPlan.blocked.length, changedObjects.comparison.length);

    // Verify catalog inspection works for a login with no table-level SELECT grants.
    await admin.query(`CREATE ROLE ${quoteDb(restrictedRole)} LOGIN PASSWORD '${restrictedPassword}'`);
    restrictedRoleCreated = true;
    await admin.query(`GRANT CONNECT ON DATABASE ${quoteDb(sourceName)} TO ${quoteDb(restrictedRole)}`);
    await admin.query(`GRANT CONNECT ON DATABASE ${quoteDb(targetName)} TO ${quoteDb(restrictedRole)}`);
    const restrictedUrl = (name: string) => {
      const url = new URL(databaseUrl(name));
      url.username = restrictedRole;
      url.password = restrictedPassword;
      return url.toString();
    };
    const restrictedSource = new pg.Pool({ connectionString: restrictedUrl(sourceName), max: 1 });
    const restrictedTarget = new pg.Pool({ connectionString: restrictedUrl(targetName), max: 1 });
    try {
      const privileges = await restrictedSource.query(
        "SELECT has_table_privilege(current_user, 'public.workers', 'SELECT') AS can_select"
      );
      assert.equal(privileges.rows[0]?.can_select, false);
      const restrictedInspection = await inspectDatabaseTransfer(
        restrictedUrl(sourceName), restrictedUrl(targetName)
      );
      assert.equal(restrictedInspection.source.tableCount, 5);
      assert.equal(restrictedInspection.target.tableCount, 5);
      assert.deepEqual(
        restrictedInspection.objectComparison.indexes,
        changedObjects.objectComparison.indexes,
        "restricted catalog access should report the same index differences"
      );
      assert.deepEqual(
        restrictedInspection.blockers,
        changedObjects.blockers,
        "restricted catalog access should preserve schema blockers"
      );
      assert.equal(restrictedInspection.sourceFeatures.triggers, 1);
      assert.equal(restrictedInspection.sourceFeatures.routines, 9);
      assert.equal(restrictedInspection.sourceFeatures.sequences, 3);
    } finally {
      await Promise.all([restrictedSource.end(), restrictedTarget.end()]);
    }

    const sourceReadOnlyPool = createReadOnlySourcePool(databaseUrl(sourceName));
    try {
      await assert.rejects(
        () => sourceReadOnlyPool.query("INSERT INTO public.workers(name) VALUES ($tag$must-not-write$tag$)"),
        (error: unknown) => Boolean(error && typeof error === "object" && "code" in error &&
          (error as { code?: string }).code === "25006")
      );
    } finally {
      await sourceReadOnlyPool.end();
    }

    const targetReadOnlyPool = createTargetPool(databaseUrl(targetName));
    try {
      await assert.rejects(
        () => targetReadOnlyPool.query("INSERT INTO public.workers(name) VALUES ($tag$must-not-write$tag$)"),
        (error: unknown) => Boolean(error && typeof error === "object" && "code" in error &&
          (error as { code?: string }).code === "25006")
      );
    } finally {
      await targetReadOnlyPool.end();
    }

    const targetPool = new pg.Pool({ connectionString: databaseUrl(targetName), max: 1 });
    try {
      await targetPool.query("CREATE TABLE public.target_only_fixture (id integer PRIMARY KEY)");
    } finally {
      await targetPool.end();
    }
    const mismatch = await inspectDatabaseTransfer(databaseUrl(sourceName), databaseUrl(targetName));
    assert.ok(mismatch.blockers.some(item => item.table === "public.target_only_fixture" && item.status === "target_only"));
  } finally {
    await admin.end();
    const cleanup = new pg.Pool({ connectionString: adminUrl, max: 1 });
    try {
      if (restrictedRoleCreated) {
        await cleanup.query(`REVOKE CONNECT ON DATABASE ${quoteDb(sourceName)} FROM ${quoteDb(restrictedRole)}`).catch(() => undefined);
        await cleanup.query(`REVOKE CONNECT ON DATABASE ${quoteDb(targetName)} FROM ${quoteDb(restrictedRole)}`).catch(() => undefined);
        await cleanup.query(`DROP ROLE IF EXISTS ${quoteDb(restrictedRole)}`);
      }
      if (targetCreated) {
        await cleanup.query("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = $1", [targetName]);
        await cleanup.query(`DROP DATABASE IF EXISTS ${quoteDb(targetName)}`);
      }
      if (sourceCreated) {
        await cleanup.query("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = $1", [sourceName]);
        await cleanup.query(`DROP DATABASE IF EXISTS ${quoteDb(sourceName)}`);
      }
    } finally {
      await cleanup.end();
    }
  }
});
